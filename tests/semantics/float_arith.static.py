# 浮点算术与打印：repr 走最短往返表示，, 与 / 混算结果。
# 守住点：float 打印不能用 %g（会丢精度），整数除法的结果类型要跟着变。
def main():
    print(1.5 + 2.25, 1.5 * 4, 10.0 / 4, 3.0 - 5.5)
    print(0.1 + 0.2)
    print(1e10, 1e-7, 1.5e300)
    print(3.0, -0.0, 2.0 ** 0.5)
    print(7 / 2, 7 // 2, 8 / 4)
    x = 1.0
    for i in range(5):
        x = x * 1.5 + 0.25
        print(i, x)
    print(float(3), float("2.5"), int(2.9), int(-2.9))
    print(1.0 == 1, 1.0 < 2, 2.5 > 2)
